def sp(n=8):return Spacer(1,n)
def pic(name,caption,desired=W):
    with PILImage.open(FIG/name) as im: source_w,source_h=im.size
    image=Image(str(FIG/name),width=desired,height=desired*source_h/source_w)
    return [image,p(caption,'cap')]
def grid(headers,rows,widths=None):
    data=[[p(escape(h),'cellh') for h in headers]]+[[p(str(c),'cell') for c in row] for row in rows]
    widths=widths or [W/len(headers)]*len(headers)
    t=Table(data,colWidths=widths,repeatRows=1,hAlign='LEFT')
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),MID),('GRID',(0,0),(-1,-1),.35,BORDER),
        ('ROWBACKGROUNDS',(0,1),(-1,-1),[WHITE,colors.HexColor('#f2f8fa')]),
        ('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),8),('RIGHTPADDING',(0,0),(-1,-1),8),
        ('TOPPADDING',(0,0),(-1,-1),7),('BOTTOMPADDING',(0,0),(-1,-1),7)]))
    return t
class Doc(BaseDocTemplate):
    def __init__(self,filename):
        super().__init__(str(filename),pagesize=A4,leftMargin=L,rightMargin=R,topMargin=TOP,bottomMargin=BOTTOM,
                         title='paceval | Auditable Multi-Step AI Computation Chains',author='paceval research demonstrator',
                         subject='Implementation and reproducibility of mathematical AI tool chains')
        frame=Frame(L,BOTTOM,W,pageh-TOP-BOTTOM,leftPadding=0,rightPadding=0,topPadding=0,bottomPadding=0)
        self.addPageTemplates(PageTemplate(id='normal',frames=[frame],onPage=self.headerfoot))
    def headerfoot(self,can,doc):
        can.saveState();can.setFillColor(MID);can.rect(0,pageh-14,pagew,14,fill=1,stroke=0)
        can.setStrokeColor(BORDER);can.line(L,39,pagew-R,39)
        can.setFont('Helvetica',7.8);can.setFillColor(MUTED)
        can.drawString(L,28,'paceval | Auditable AI Computation Chains | reproducible research demonstrator')
        can.drawRightString(pagew-R,28,f'12 November 2026  |  {doc.page}')
        can.restoreState()

