// WP027: Reusable mathematical process-quality scores with the original paceval C++ API.
// All generated process records and labels are synthetic and have no factory calibration.
// paceval computes risk-score expressions. C++ owns dimensional normalization, validation,
// reproducible records, threshold policies, and independent model/label diagnostics.
#include "paceval_main.h"
#include <algorithm>
#include <array>
#include <cmath>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>
namespace fs=std::filesystem;
namespace {
using Args=std::array<double,5>;
constexpr char VARS[]="t p s v w";
void require(bool v,const std::string& s){if(!v)throw std::runtime_error(s);}
struct RNG{std::uint64_t state=20261112;std::uint64_t next(){state^=state>>12;state^=state<<25;state^=state>>27;return state*2685821657736338717ULL;}double unit(){return (next()>>11)*0x1.0p-53;}};
struct Rule{int id=0,family=0;double a=0,b=0,c=0;std::string expr;PACEVAL_HANDLE handle=nullptr;};
// Inputs t,p,s,v,w are normalized dimensionless deviations; physical sensor units
// must be standardized by a trained, controlled preprocessor before such scores can be used.
// Five deliberately different nonlinear formula families. The output is a proxy score
// between zero and one, NOT a calibrated probability of real manufactured scrap.
double native(const Rule& r,const Args& x){double t=x[0],p=x[1],s=x[2],v=x[3],w=x[4],z=0;
 switch(r.family){
 case 0:z=r.a*t+r.b*p+r.c*s+0.35*v+0.25*w;break;
 case 1:z=r.a*t*t+r.b*p*p+r.c*s*s+0.30*v-0.70;break;
 case 2:z=r.a*t*p+r.b*s*v+r.c*w+0.12*t*t-0.15;break;
 case 3:z=r.a*std::sin(t)+r.b*std::cos(p)+r.c*s*w+0.30*v;break;
 default:z=r.a*std::log(1+t*t)+r.b*std::sqrt(1+p*p)+r.c*v*w+0.15*s-0.45;break;
 }return 1.0/(1.0+std::exp(-z));}
std::string expression(const Rule& r){std::ostringstream o;o<<std::setprecision(17);
 o<<"1/(1+exp(-(";
 switch(r.family){
 case 0:o<<r.a<<"*t+"<<r.b<<"*p+"<<r.c<<"*s+0.35*v+0.25*w";break;
 case 1:o<<r.a<<"*t*t+"<<r.b<<"*p*p+"<<r.c<<"*s*s+0.30*v-0.70";break;
 case 2:o<<r.a<<"*t*p+"<<r.b<<"*s*v+"<<r.c<<"*w+0.12*t*t-0.15";break;
 case 3:o<<r.a<<"*sin(t)+"<<r.b<<"*cos(p)+"<<r.c<<"*s*w+0.30*v";break;
 default:o<<r.a<<"*ln(1+t*t)+"<<r.b<<"*sqrt(1+p*p)+"<<r.c<<"*v*w+0.15*s-0.45";break;
 }o<<")))";return o.str();}
std::vector<Rule> rules(){std::vector<Rule> a;for(int f=0;f<5;++f)for(int j=0;j<10;++j){Rule r;r.id=f*10+j+1;r.family=f;r.a=0.22+0.025*j+0.013*f;r.b=0.18+0.018*j;r.c=0.14+0.014*j;r.expr=expression(r);a.push_back(r);}return a;}
class Engine{std::vector<PACEVAL_HANDLE> handles;public:
 Engine(){require(paceval_InitializeLibrary(nullptr),"paceval SDK initialization failed");}
 ~Engine(){for(auto h:handles)if(h)paceval_DeleteComputation(h);paceval_FreeLibrary();}
 PACEVAL_HANDLE create(const std::string& e){auto h=paceval_CreateComputation(e.c_str(),5,VARS,false,nullptr);require(h&&!paceval_GetIsError(h),"failed to create paceval graph: "+e);handles.push_back(h);return h;}
 double eval(PACEVAL_HANDLE h,const Args& x){Args mutable_x=x;double z=paceval_dGetComputationResult(h,mutable_x.data(),nullptr,nullptr);require(!paceval_GetIsError(h)&&std::isfinite(z),"paceval scalar evaluation failed");return z;}
 std::vector<double> batch(PACEVAL_HANDLE h,const std::vector<Args>& x){std::vector<double> v(x.size()*5),out(x.size());std::vector<int> errs(x.size(),-1);for(size_t i=0;i<x.size();++i)for(int k=0;k<5;++k)v[5*i+k]=x[i][k];bool failed=paceval_dGetComputationResultExt(h,v.data(),(unsigned long)x.size(),out.data(),nullptr,nullptr,errs.data());require(!failed,"paceval batch failed");for(size_t i=0;i<x.size();++i)require(errs[i]==0&&std::isfinite(out[i]),"paceval batch result invalid");return out;}
};
Args sample(RNG& r){return {-1.6+3.2*r.unit(),-1.6+3.2*r.unit(),-1.6+3.2*r.unit(),-1.6+3.2*r.unit(),-1.6+3.2*r.unit()};}
// Independent deterministic synthetic label mechanism, separate from all fifty
// score formula versions; the labels are not generated by the prediction itself.
double synthetic_defect_chance(const Args& x){double z=-1.65+0.75*x[0]*x[0]+0.48*x[1]*x[1]+0.36*x[3]+0.18*x[4]*x[2];return 1/(1+std::exp(-z));}
void audit(double got,double ref,double& worst){double d=std::abs(got-ref);worst=std::max(worst,d);require(d<=1e-11*(1+std::abs(ref)),"paceval numerical audit failed");}
void valid(const Args& x){for(double v:x)require(std::isfinite(v)&&v>=-2&&v<=2,"out-of-contract normalized sensor input");}
int run(const fs::path& out){fs::create_directories(out);Engine engine;auto all=rules();for(auto& r:all)r.handle=engine.create(r.expr);
 Rule revised=all[0];revised.id=51;revised.a+=0.07;revised.expr=expression(revised);revised.handle=engine.create(revised.expr);
 std::ofstream registry(out/"score_registry.csv");registry<<"score_id,family,version,coefficient_a,coefficient_b,coefficient_c,expression\n";
 for(const auto& r:all)registry<<r.id<<","<<r.family+1<<",1,"<<r.a<<","<<r.b<<","<<r.c<<",\""<<r.expr<<"\"\n";
 registry<<"51,1,2,"<<revised.a<<","<<revised.b<<","<<revised.c<<",\""<<revised.expr<<"\"\n";
 std::ofstream records(out/"quality_records.csv");records<<"record_id,score_id,temperature_dev,pressure_dev,speed_dev,vibration_dev,wear_dev,synthetic_defect_label,score,inspect_flag\n";
 RNG rng;std::array<int,50> counts{},flags{},positives{},truepos{},falsepos{};std::array<double,50> sums{};size_t scalar=0,batch=0;double worst=0;
 for(int i=0;i<10000;++i){auto& r=all[i%50];Args a=sample(rng);valid(a);double score=engine.eval(r.handle,a);audit(score,native(r,a),worst);++scalar;
 // Inspect threshold is an illustrative policy; scores are NOT calibrated probabilities.
 int inspect=(score>=0.60);int label=(rng.unit()<synthetic_defect_chance(a));int k=i%50;
 ++counts[k];flags[k]+=inspect;positives[k]+=label;truepos[k]+=inspect&&label;falsepos[k]+=inspect&&!label;sums[k]+=score;
 records<<std::setprecision(17)<<i+1<<","<<r.id;for(double v:a)records<<","<<v;records<<","<<label<<","<<score<<","<<inspect<<"\n";}
 std::ofstream stats(out/"score_summary.csv");stats<<"score_id,family,mean_score,inspection_rate,label_rate,true_positive_count,false_positive_count\n";
 for(int k=0;k<50;++k)stats<<k+1<<","<<all[k].family+1<<","<<sums[k]/counts[k]<<","<<double(flags[k])/counts[k]<<","<<double(positives[k])/counts[k]<<","<<truepos[k]<<","<<falsepos[k]<<"\n";
 std::ofstream surface(out/"quality_surface.csv");surface<<"temperature_dev,pressure_dev,score\n";
 for(int i=0;i<=60;++i)for(int j=0;j<=60;++j){Args a={-1.5+0.05*i,-1.5+0.05*j,0.25,0.3,0.2};double p=engine.eval(all[0].handle,a);audit(p,native(all[0],a),worst);++scalar;surface<<a[0]<<","<<a[1]<<","<<std::setprecision(17)<<p<<"\n";}
 std::ofstream versions(out/"formula_versions.csv");versions<<"temperature_dev,score_version_1,score_version_2\n";
 for(int i=0;i<=60;++i){Args a={-1.5+0.05*i,0.3,0.2,0.15,0.1};double v1=engine.eval(all[0].handle,a),v2=engine.eval(revised.handle,a);audit(v1,native(all[0],a),worst);audit(v2,native(revised,a),worst);scalar+=2;versions<<a[0]<<","<<v1<<","<<v2<<"\n";}
 RNG br;for(auto& r:all){std::vector<Args> a;for(int i=0;i<32;++i)a.push_back(sample(br));auto values=engine.batch(r.handle,a);for(int i=0;i<32;++i){audit(values[i],native(r,a[i]),worst);++batch;}}
 std::ofstream log(out/"sdk_execution.txt");log<<std::setprecision(17)<<"STATUS PASS\nGRAPH_COUNT 51\nRECORDS 10000\nSCALAR_CHECKS "<<scalar<<"\nBATCH_CHECKS "<<batch<<"\nSURFACE_POINTS 3721\nMAX_ABS_INTERNAL_AUDIT "<<worst<<"\n";
 std::cout<<"PASS 51 graphs 10000 records "<<scalar<<" scalar "<<batch<<" batch\n";return 0;}
}
int main(int argc,char** argv){try{fs::path out="examples";for(int i=1;i<argc;++i)if(std::string(argv[i])=="--out"&&i+1<argc)out=argv[++i];return run(out);}catch(const std::exception& e){std::cerr<<"FAIL: "<<e.what()<<"\n";return 1;}}
