#!/usr/bin/env python3
"""Independent 90-digit physical-balance reference, separate from paceval expressions.
Reads the ACTUAL C++ application CSV, never generates a fake paceval result.
"""
import csv,math,sys,json,hashlib
from pathlib import Path
from mpmath import mp
mp.dps=90
ROOT=Path(__file__).resolve().parents[1]
RESULTS=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'results'
def xf(x):
    # Reference uses exact binary double decoded from user/SDK decimal data.
    f=float(x)
    num,den=f.as_integer_ratio()
    return mp.mpf(num)/den
def within(x,y,relative=mp.mpf('2e-10'),absolute=mp.mpf('1e-10')):
    return abs(x-y)<= absolute+relative*max(abs(x),abs(y))
def ref(row,ver,alpha=None):
    T=xf(row['T_K']);L=xf(row['W_m']);h3=xf(row['H3_m']);c3=xf(row['C3_invK']);beta=xf(row['beta'])
    gel=mp.mpf('0.4');a=xf(row['alpha']) if alpha is None else alpha
    h=[mp.mpf('0.0005'),mp.mpf('0.00007'),h3]
    E=[mp.mpf('130e9'),mp.mpf('2.5e9'),mp.mpf('8e9')*(1+mp.mpf('0.8')*(a-gel) if ver==2 else 1)]
    nu=[mp.mpf('.28'),mp.mpf('.35'),mp.mpf('.32')]
    cte=[mp.mpf('2.6e-6'),mp.mpf('45e-6'),c3]
    e=[c*(T-mp.mpf('423.15')) for c in cte]
    if ver==2:e[2]-=beta*(a-gel)/(1-gel)
    z=[mp.mpf('0')]
    for thick in h:z.append(z[-1]+thick)
    moduli=[ei/(1-ni) for ei,ni in zip(E,nu)]
    # Independent summation of laminate force/moment resultants, derived
    # from integrals over each layer [z_i,z_i+1].
    A=B=D=N=M=mp.mpf('0')
    for i in range(3):
        lo,hi=z[i:i+2];mi=moduli[i]
        A+=mi*(hi-lo)
        B+=mi*(hi**2-lo**2)/2
        D+=mi*(hi**3-lo**3)/3
        N+=mi*e[i]*(hi-lo)
        M+=mi*e[i]*(hi**2-lo**2)/2
    denom=A*D-B**2
    assert denom>0
    k=(A*M-B*N)/denom
    eps=(D*N-B*M)/denom
    stress=max(abs(moduli[i]*(eps+k*zv-e[i])) for i in range(3) for zv in (z[i],z[i+1]))
    w=k*L**2/8
    dNdt=sum(moduli[i]*cte[i]*h[i] for i in range(3))
    dMdt=sum(moduli[i]*cte[i]*(z[i+1]**2-z[i]**2)/2 for i in range(3))
    dT=(A*dMdt-B*dNdt)/denom
    if ver==2:
        slope=-(a-gel)/(1-gel)
        dNdb=moduli[2]*h[2]*slope
        dMdb=moduli[2]*(z[3]**2-z[2]**2)*slope/2
        db=(A*dMdb-B*dNdb)/denom
    else: db=mp.mpf('0')
    return dict(k=k,warp=w,stress=stress,dt=dT,db=db)
def rows(path):
    with path.open(newline='',encoding='utf-8') as f:return list(csv.DictReader(f))
def check():
    screening=rows(RESULTS/'screening.csv')
    assert len(screening)==2560
    sampled=[screening[i] for i in range(0,len(screening),9)]
    # Additional all-limit and corner samples.
    sampled+=screening[:10]+screening[-10:]
    checks=0;maxrelative=mp.mpf('0');details=[]
    for r in sampled:
        ver=int(r['model']);n=ref(r,ver)
        for field,key,atol in [('signed_curvature_inv_m','k','1e-8'),('signed_center_edge_warpage_m','warp','1e-12'),('peak_endpoint_stress_Pa','stress','0.005'),('dcurvature_dT_inv_mK','dt','1e-8'),('dcurvature_dbeta_inv_m','db','1e-5')]:
            actual=xf(r[field]);target=n[key]
            if not within(actual,target,mp.mpf('3e-9'),mp.mpf(atol)):
                raise AssertionError(f'{r["case_id"]} v{ver} {field}: {actual} vs {target}')
            error=abs(actual-target)
            scale=max(abs(target),mp.mpf('1e-10'))
            maxrelative=max(maxrelative,error/scale)
            checks+=1
        wm=xf(r['warpage_margin_m']);sm=xf(r['stress_margin_Pa']);guard=xf(r['screen_guard'])
        assert guard in (0,1) and guard==int(wm>=0 and sm>=0)
        checks+=1
        details.append(dict(case_id=r['case_id'],model=ver,curvature_abs_error=str(abs(xf(r['signed_curvature_inv_m'])-n['k'])),stress_abs_error=str(abs(xf(r['peak_endpoint_stress_Pa'])-n['stress']))))
    # CSV import/export schema, finiteness, and independent model comparisons.
    comparator=rows(RESULTS/'model_comparison.csv');assert len(comparator)==1280
    for r in comparator[::11]:
        pairs=[(r['V1_curvature_inv_m'],r['V2_curvature_inv_m'],r['delta_curvature_inv_m']), (r['V1_warp_m'],r['V2_warp_m'],r['delta_warp_m'])]
        for x,y,delta in pairs:
            if not within(xf(delta),xf(y)-xf(x),mp.mpf('8e-10'),mp.mpf('2e-11')):raise AssertionError('Model delta mismatch')
            checks+=1
    # Warpage surface is generated by a separate paceval graph on 41x41 grid.
    surface=rows(RESULTS/'deflection_surface.csv');assert len(surface)==2*41*41
    for r in surface[::43]:
        ver=int(r['model']);last=[p for p in rows(RESULTS/'thermal_profile.csv') if int(p['model'])==ver]
        # The reference geometry uses initial baseline T=298.15 K rather than the temperature sweep.
        baserow={'T_K':'298.15','W_m':'.020','H3_m':'.00055','C3_invK':'.00002','beta':'.0018','alpha':'.85'}
        k=ref(baserow,ver)['k']
        value=k*(xf(r['x_m'])**2+xf(r['y_m'])**2)/2
        if not within(value,xf(r['deflection_m']),mp.mpf('3e-9'),mp.mpf('2e-11')):raise AssertionError('Surface mismatch')
        checks+=1
    # Independent high precision integration of the cure state with the recorded temperature program.
    cure=rows(RESULTS/'cure_profile.csv');assert len(cure)==181
    def T(i):
        return mp.mpf('423.15') if i<=65 else mp.mpf('423.15')-mp.mpf('125')*mp.mpf(i-65)/90 if i<=155 else mp.mpf('298.15')
    def rhs(a,t):
        r=mp.mpf('8.31446261815324')
        one=mp.mpf('.0004')*mp.exp((-mp.mpf('55000')/r)*(1/t-1/mp.mpf('423.15')))
        two=mp.mpf('.002')*mp.exp((-mp.mpf('65000')/r)*(1/t-1/mp.mpf('423.15')))
        return (one+two*a)*(1-a)
    alpha=mp.mpf('.43')
    for i,r in enumerate(cure):
        if not within(alpha,xf(r['degree_of_cure']),mp.mpf('4e-9'),mp.mpf('4e-11')):raise AssertionError(f'Cure ODE mismatch at {i}')
        checks+=1
        if i==180:break
        a=T(i);b=T(i+1);dt=mp.mpf('60')
        k1=rhs(alpha,a);k2=rhs(alpha+dt*k1/2,(a+b)/2);k3=rhs(alpha+dt*k2/2,(a+b)/2);k4=rhs(alpha+dt*k3,b)
        alpha=min(mp.mpf(1),alpha+dt*(k1+2*k2+2*k3+k4)/6)
    report={'research_scope':'synthetic laminate screening; not package qualification', 'precision_decimal_digits':90, 'high_precision_endvalue_rows':len(sampled),'high_precision_checks':checks,'high_precision_check_status':'PASS', 'max_relative_error_audit_only':str(maxrelative),'binary_input_interpretation':'CSV double values represented exactly in mpmath using as_integer_ratio', 'cure_ode':'independent 90-digit RK4 verification of logged time program', 'review_note':'Scientific model validity requires calibration and independent material/FEM testing'}
    (RESULTS/'scientific_audit.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    with (RESULTS/'high_precision_audit.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=['case_id','model','curvature_abs_error','stress_abs_error']);w.writeheader();w.writerows(details)
    print(f"HIGH PRECISION PASS: {len(sampled)} sampled end-value rows, {checks} checks, independent cure-profile RK4")
if __name__=='__main__':check()
