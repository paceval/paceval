#!/usr/bin/env python3
"""Independent native reference: reproduces 18 complete battery traces and energy summaries.
The trace is generated by the original paceval program; oracle never calls paceval.
"""
import csv, math, json, argparse
from pathlib import Path

def current(profile,step):
 j=step%160
 if profile==0:return 2.7 if j<38 else 4.8 if j<60 else 0 if j<86 else -1.8 if j<115 else 2.1
 if profile==1:return 3.3 if j<85 else 5.2 if j<110 else 0 if j<130 else 2.2
 return -2.5 if j<85 else -1 if j<110 else 0 if j<145 else 1.5

def step(z,p1,p2,T,I,Ta,age,ver):
 o=3.2+.93*z+.10*(2/(1+math.exp(-13*(z-.5)))-1)+.00035*(T-25)
 r0=.021*(1+.7*(1-z)**2)*math.exp(.017*(25-T))*age
 r1=.012*(1+.35*(1-z))*math.exp(.013*(25-T))*age
 r2=.019*(1+.20*(1-z))*math.exp(.009*(25-T))*age
 tau1=32*(1+.30*(1-z))*math.exp(.008*(25-T));tau2=175*(1+.25*(1-z))*math.exp(.006*(25-T))
 v=o-I*r0-p1-(p2 if ver==2 else 0)
 heat=I**2*r0+p1**2/r1+(p2**2/r2 if ver==2 else 0)
 nextz=z-I*2*age/(3600*3.2)
 nextp1=p1*math.exp(-2/tau1)+I*r1*(1-math.exp(-2/tau1))
 nextp2=0 if ver==1 else p2*math.exp(-2/tau2)+I*r2*(1-math.exp(-2/tau2))
 nextT=T+2*(heat-.15*(T-Ta))/130
 cost=.32*(v-3.8)**2+.033*(I/3.2)**2+.014*((T-25)/15)**2+.014*(r0/.025)**2+.008*((z-.65)/.35)**2
 return (nextz,nextp1,nextp2,nextT,v,heat,I*v,I*o,I**2*r0,I*(p1+(p2 if ver==2 else 0)),cost)

def verify(root):
 summaries=list(csv.DictReader((root/'results/scenario_summary.csv').open()))
 traces={}
 with (root/'examples/trace_samples.csv').open() as f:
  for r in csv.DictReader(f):traces[(int(r['scenario_id']),int(r['step']))]=r
 n=0;maxerr=0;maxPower=0;scenarioAudit=[]
 def eq(got,ref,label):
  nonlocal n,maxerr
  d=abs(float(got)-ref)/(1+abs(ref));maxerr=max(maxerr,d);n+=1
  if d>1e-9:raise AssertionError(f'{label} result mismatch {got} versus {ref}; scaled {d}')
 for r in summaries:
  profile=int(r['profile']);ver=int(r['version']);Ta=float(r['ambient_C']);age=float(r['age_factor']);steps=int(r['steps']);cid=int(r['scenario_id']);
  z,p1,p2,T=.74,0.,0.,Ta
  eterm=eocv=eohm=epol=eheat=ah=score=0.;vmin=100;vmax=-100;tmax=-100;countlo=counthi=0;maxres=0
  for i in range(steps):
   I=current(profile,i)
   nz,np1,np2,nT,V,heat,P,OC,oh,pol,cost=step(z,p1,p2,T,I,Ta,age,ver)
   if (cid,i) in traces:
    x=traces[(cid,i)];
    for field,expect in [('soc',z),('polar1_V',p1),('polar2_V',p2),('temperature_C',T),('terminal_voltage_V',V),('current_A',I),('heat_proxy_W',heat),('terminal_power_W',P),('ocv_V',OC/I if I else 3.2+.93*z+.1*(2/(1+math.exp(-13*(z-.5)))-1)+.00035*(T-25))]:eq(x[field],expect,f'case {cid} {i} {field}')
   eterm+=P*2/3600;eocv+=OC*2/3600;eohm+=oh*2/3600;epol+=pol*2/3600;eheat+=heat*2/3600;ah+=I*2/3600;score+=cost*2
   residual=OC-P-oh-pol;maxres=max(maxres,abs(residual));vmin=min(vmin,V);vmax=max(vmax,V);tmax=max(tmax,nT)
   countlo+=int(V<2.8);counthi+=int(V>4.25)
   z,p1,p2,T=nz,np1,np2,nT
  for k,x in [('final_soc',z),('final_temperature_C',T),('max_temperature_C',tmax),('min_voltage_V',vmin),('max_voltage_V',vmax),('net_discharge_Ah',ah),('terminal_energy_Wh',eterm),('ocv_energy_Wh',eocv),('ohmic_energy_Wh',eohm),('polarization_power_energy_Wh',epol),('resistive_heat_proxy_Wh',eheat),('tracking_score_integral',score)]:eq(r[k],x,f'case {cid} {k}')
  eq(r['voltage_lower_count'],countlo,f'case {cid} voltage lower');eq(r['voltage_upper_count'],counthi,f'case {cid} voltage upper')
  if abs(eocv-eterm-eohm-epol)>1e-8:raise AssertionError('power energy identity violation')
  maxPower=max(maxPower,maxres)
  scenarioAudit.append({'scenario_id':cid,'verified_steps':steps,'terminal_energy_Wh':eterm,'final_soc':z,'final_T_C':T})
 report={'passed':True,'independent_cpp_equivalent_python_float_checks':n,'scenarios':len(summaries),'max_scaled_error':maxerr,'max_algebraic_power_residual_W':maxPower,'verified_time_steps_per_scenario':min(int(r['steps']) for r in summaries),'note':'synthetic model, algebraic power identity does not validate physical thermal losses; no performance conclusions'}
 (root/'results/independent_trajectory_audit.json').write_text(json.dumps(report,indent=2)+'\n')
 print('Independent complete trace/energy audit PASS',n,'checks across',len(summaries),'scenarios; max scaled error',maxerr)
 return report
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1]);a=p.parse_args();verify(a.root)
