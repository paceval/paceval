#!/usr/bin/env python3
"""Symbolically generate the actual constant version-pinned paceval formula registry.
Generation is a reproducibility step only: at runtime C++ evaluates all formulas in paceval.
Using analytic Lie derivatives avoids unstable differentiation of noisy trajectory samples.
"""
from pathlib import Path
import json, csv
import sympy as s
ROOT=Path(__file__).resolve().parent.parent
x,v,y,w,mu,zeta,t=s.symbols('x v y w mu zeta t',real=True)
r=s.sqrt(x*x+y*y)
H=(x*x+v*v+4*y*y+w*w)/2
Hx=(x*x+v*v)/2
Hy=(4*y*y+w*w)/2
L=x*w-y*v
K=(v*v+w*w)/2-mu/r
Ax=w*L-mu*x/r
Ay=-v*L-mu*y/r
Q=v*v+2*zeta*x*v+x*x
I=s.exp(2*zeta*t)*Q
models={
 'oscillator': {
  'vector': {x:v,v:-x,y:w,w:-4*y},
  'candidates': [
   ('osc_E_x',Hx,True,'E_x'),('osc_E_y',Hy,True,'E_y'),('osc_E_total',H,True,'E_x+E_y'),('osc_E_x_squared',Hx**2,True,'E_x dependent'),
   ('osc_position_x',x,False,''),('osc_velocity_x',v,False,''),('osc_position_y',y,False,''),('osc_velocity_y',w,False,''),
   ('osc_cross_xv',x*v,False,''),('osc_cross_yw',y*w,False,''),('osc_position_x_squared',x*x,False,''),('osc_velocity_x_squared',v*v,False,'')]
 },
 'kepler': {
  'vector': {x:v,y:w,v:-mu*x/r**3,w:-mu*y/r**3},
  'candidates': [
   ('kep_energy',K,True,'energy'),('kep_angular_momentum',L,True,'angular momentum'),('kep_LRL_x',Ax,True,'LRL vector x'),('kep_LRL_y',Ay,True,'LRL vector y'),
   ('kep_energy_squared',K**2,True,'energy dependent'),('kep_angular_momentum_squared',L**2,True,'angular momentum dependent'),
   ('kep_position_x',x,False,''),('kep_position_y',y,False,''),('kep_velocity_x',v,False,''),('kep_velocity_y',w,False,''),
   ('kep_radius_squared',x*x+y*y,False,''),('kep_mixed_xy',x*y,False,'')]
 },
 'damped': {
  'vector': {x:v,v:-x-2*zeta*v},
  'candidates': [
   ('damp_time_corrected_energy',I,True,'time-dependent energy'),('damp_time_corrected_energy_squared',I**2,True,'dependent function of invariant'),
   ('damp_raw_energy',(v*v+x*x)/2,False,''),('damp_position_x',x,False,''),('damp_velocity_x',v,False,''),
   ('damp_cross_xv',x*v,False,''),('damp_position_squared',x*x,False,''),('damp_velocity_squared',v*v,False,''),
   ('damp_exp_position',s.exp(zeta*t)*x,False,''),('damp_exp_velocity',s.exp(zeta*t)*v,False,''),
   ('damp_time',t,False,''),('damp_x_plus_v',x+v,False,'')]
 }
}
vars=[x,v,y,w,mu,zeta,t]
def paceval(e):
    # Fixed, explicit finite expressions with supported + - * / ^ sqrt exp operators
    return s.sstr(e).replace('**','^')
def quote(s0):return '"'+s0.replace('\\','\\\\').replace('"','\\"')+'"'
items=[]
for model,m in models.items():
    for id_,expr,truth,family in m['candidates']:
        # IMPORTANT: do NOT simplify the numeric Lie derivative to literal zero.
        # Preserve the component-wise chain rule as an explicit paceval calculation
        # so its numerical cancellation is actually exercised by the real engine.
        terms=[s.diff(expr,t)]
        terms += [s.Mul(s.diff(expr,variable),rhs,evaluate=False) for variable,rhs in m['vector'].items()]
        d=s.Add(*terms,evaluate=False)
        if truth:
            chk=s.simplify(d)
            if chk!=0:
                raise ValueError(f'Lie derivative not zero for {id_}: {chk}')
        inv=paceval(expr)
        lie=paceval(d)
        # Avoid returning library-native abs requiring interval behavior; sqrt(squared) is nonnegative.
        normalized='sqrt(('+lie+')^2)/(1+sqrt(('+inv+')^2))'
        items.append({'model':model,'id':id_,'expression':inv,'lie_expression':lie,
                      'normalized_lie_expression':normalized,
                      'squared_lie_expression':'('+lie+')^2',
                      'known_invariant':int(truth),'independent_family':family})
assert len(items)==36
with (ROOT/'results'/'formula_registry.csv').open('w',newline='') as f:
    wr=csv.DictWriter(f,fieldnames=list(items[0]));wr.writeheader();wr.writerows(items)
(ROOT/'src'/'generated_registry.h').write_text('// GENERATED by generate_registry.py with SymPy. All actual evaluations use original paceval C++ API.\n'
 + '#pragma once\n#include <string>\n#include <vector>\nstruct FormulaDef {const char* model;const char* id;const char* expression;const char* lie;const char* normalized_lie;const char* lie_sq;bool known;const char* family;};\n'
 + 'inline std::vector<FormulaDef> makeFormulaDefs(){ return {\n'
 + '\n'.join('  {'+', '.join(map(quote,[q['model'],q['id'],q['expression'],q['lie_expression'],q['normalized_lie_expression'],q['squared_lie_expression']]))+', '+('true' if q['known_invariant'] else 'false')+', '+quote(q['independent_family'])+'},' for q in items)
 + '\n};}\n')
print('registry:',len(items),'candidate formulas and',len(items)*4,'actual paceval graphs')
for m in models:print(m, sum(z['model']==m for z in items))
