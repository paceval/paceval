#!/usr/bin/env python3
"""Regenerate publication figures from the included example result files.

The hero illustration is an independent promotional artwork and cannot be
regenerated by this script. All numbered scientific figures are data-derived
or explicitly labeled conceptual. They make no performance claims.
"""
from collections import defaultdict
from pathlib import Path
import argparse, csv, math
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch

NAVY='#0b2340'; BLUE='#16678f'; CYAN='#16a5bd'; GREEN='#14a886'; ORANGE='#d9893b'; GREY='#66798a'

def rows(file):
    with open(file,newline='') as f:return list(csv.DictReader(f))

def save(fig,path):
    fig.savefig(path,dpi=180,bbox_inches='tight',facecolor='white')
    plt.close(fig)

def workflow(path):
    fig,ax=plt.subplots(figsize=(11.2,3.6));ax.set_xlim(0,12);ax.set_ylim(0,3);ax.axis('off')
    blocks=[(0.3,'Precomputed\nmodel outputs\n(3 synthetic traces)'),(3.35,'paceval SDK\n50 score graphs\n+ 50 margin graphs'),(6.5,'C++ host\nthreshold + EMA\nhysteresis'),(9.6,'Independent\nverification\nand CSV audit')]
    for i,(x,t) in enumerate(blocks):
        patch=FancyBboxPatch((x,.88),2.2,1.35,boxstyle='round,pad=0.12,rounding_size=.12',fc=('#e2f1f5' if i!=1 else '#ddf2ed'),ec=CYAN if i!=1 else GREEN,lw=1.5)
        ax.add_patch(patch);ax.text(x+1.1,1.56,t,ha='center',va='center',color=NAVY,fontsize=11,fontweight='medium')
        if i<3:ax.add_patch(FancyArrowPatch((x+2.35,1.55),(blocks[i+1][0]-.11,1.55),arrowstyle='-|>',mutation_scale=18,lw=1.7,color=BLUE))
    ax.text(6,2.78,'Validated edge postprocessing boundary',fontweight='bold',ha='center',fontsize=17,color=NAVY)
    ax.text(6,.35,'No neural-network inference, device I/O, or hardware control is performed by this demonstrator',ha='center',fontsize=10,color=GREY)
    save(fig,path)

def score_surface(path):
    fig,ax=plt.subplots(figsize=(8.5,5.2))
    p=np.linspace(0,1,150);x=np.linspace(-4,4,190)
    PP,XX=np.meshgrid(p,x)
    # Illustrative static slice: p2=0.35, eps=0.015, a=0.13,b=1.0
    z=PP/(PP+0.35+0.015)+0.13*np.tanh(XX)
    im=ax.contourf(PP,XX,z,levels=25,cmap='viridis');cbar=fig.colorbar(im,ax=ax);cbar.set_label('Synthetic score (dimensionless)')
    ax.set_xlabel('First model channel p1');ax.set_ylabel('Normalized auxiliary feature x')
    ax.set_title('Illustrative score surface · base formula',color=NAVY,fontweight='bold')
    fig.text(.13,.02,'Slice: p2=0.35, eps=0.015, a=0.13, b=1.0; not calibrated model confidence',fontsize=9,color=GREY)
    save(fig,path)

def decision_trace(path,data):
    fig,axs=plt.subplots(3,1,figsize=(9.5,8.0),sharex=True)
    for ax,trace in zip(axs,['vision','vibration','thermal']):
        r=[v for v in data if v['trace_id']==trace and v['version_id']=='formula_00_00']
        xs=[int(v['step']) for v in r]
        score=[float(v['score']) for v in r];ema=[float(v['ema']) for v in r]
        th=[float(v['threshold']) for v in r]
        ax.plot(xs,score,label='paceval score',c=CYAN,lw=1.4)
        ax.plot(xs,ema,label='host EMA',c=BLUE,lw=2)
        ax.plot(xs,th,label='host threshold',c=ORANGE,lw=1.2,ls='--')
        ax.fill_between(xs,min(min(score),min(th))-.05,max(max(score),max(th))+.05,where=[int(v['latched'])==1 for v in r],color=GREEN,alpha=.07,label='latched ON')
        ax.set_ylabel(trace.title()+'\nscore');ax.grid(alpha=.2)
    axs[0].legend(loc='upper right',ncol=4,fontsize=8)
    axs[-1].set_xlabel('Synthetic sample step')
    fig.suptitle('Scoring, host-owned smoothing and threshold decisions',fontsize=16,color=NAVY,fontweight='bold')
    fig.tight_layout(rect=(0,0,1,.96));save(fig,path)

def versions(path,data):
    r=[v for v in data if v['trace_id']=='vision' and int(v['step'])==28]
    fig,ax=plt.subplots(figsize=(9.8,4.6));xs=np.arange(len(r));ys=[float(v['score']) for v in r]
    cs=[BLUE,CYAN,GREEN,ORANGE,'#8969bd']
    for family in range(5):
        yy=ys[10*family:10*(family+1)];ax.plot(xs[10*family:10*(family+1)],yy,marker='o',ms=4,lw=1.7,color=cs[family],label=f'Family {family}')
    ax.set_xlabel('Versioned mathematical expression (50)');ax.set_ylabel('Score at fixed synthetic sample')
    ax.set_title('Configuration changes evaluated without editing C++ expressions',color=NAVY,fontweight='bold')
    ax.grid(alpha=.2);ax.legend(ncol=5,loc='upper center',fontsize=8)
    fig.text(.14,.02,'Controlled families/revision weights are synthetic mathematical examples, not calibrated production policies',fontsize=9,color=GREY)
    save(fig,path)

def interval(path,data):
    fig,ax=plt.subplots(figsize=(10.5,4.6))
    idx=np.arange(len(data));center=np.array([float(r['value']) for r in data])
    low=np.array([float(r['lower']) for r in data]);up=np.array([float(r['upper']) for r in data]);
    # Error widths typically at floating point scale; normalize by a fixed scale so
    # the near-machine-precision intervals are legible without faking an envelope.
    low_err=np.maximum(center-low,0);up_err=np.maximum(up-center,0)
    ax.bar(idx-.16,low_err/1e-15,width=.32,color=BLUE,label='value − lower')
    ax.bar(idx+.16,up_err/1e-15,width=.32,color=GREEN,label='upper − value')
    ax.axhline(0,c=NAVY,lw=.8)
    ax.set_xlabel('Independent pointwise TINC sample');ax.set_ylabel('Reported interval half-width / 1e−15')
    ax.set_title('TINC interval widths for 24 selected sample/formula pairs',color=NAVY,fontweight='bold')
    ax.legend();ax.grid(axis='y',alpha=.2)
    fig.text(.13,.02,'Containment checked separately against 110-digit mpmath; pointwise samples are not a global interval proof',fontsize=9,color=GREY)
    save(fig,path)

def errors(path,data):
    # This figure deliberately uses a 110-digit independent oracle rather than
    # redoing the same native C++-style evaluation (which can be bit-identical).
    import mpmath as mp
    mp.mp.dps = 110
    family={k:[] for k in range(5)}
    for r in data:
        v={k:mp.mpf(float(r[k])) for k in ('p1','p2','x','quality','a','b','eps')}
        p1,p2,x,q,a,b,eps=(v[k] for k in ('p1','p2','x','quality','a','b','eps'))
        f=int(r['family']);w=mp.mpf(float(r['weight']))
        term=[q-mp.mpf('0.5'),(p1-p2)*q,x*x/(1+x*x),(p1-p2)**2,mp.sin(x)*q][f]
        reference=p1/(p1+p2+eps)+a*mp.tanh(b*x)+w*term
        difference=abs(mp.mpf(float(r['score']))-reference)
        family[f].append(float(difference))
    fig,ax=plt.subplots(figsize=(9.0,4.5))
    data_err=[np.array(family[k])+1e-20 for k in range(5)]
    ax.boxplot(data_err,showfliers=False)
    ax.set_yscale('log');ax.set_xticks(range(1,6),[f'Family {i}' for i in range(5)])
    ax.set_ylabel('Absolute error vs independent 110-digit reference')
    ax.set_title('Numerical agreement across formula families',color=NAVY,fontweight='bold')
    ax.grid(axis='y',alpha=.2)
    fig.text(.13,.02,'Small display floor of 1e−20 for a log scale; source: recorded binary64 outputs',fontsize=9,color=GREY)
    save(fig,path)

def boundaries(path,data):
    fig,axs=plt.subplots(1,2,figsize=(10.8,4.7))
    r=[x for x in data if x['version_id']=='formula_00_00']
    p=[float(x['p1'])+float(x['p2']) for x in r]; y=[float(x['score']) for x in r]
    axs[0].scatter(p,y,s=12,c=BLUE,alpha=.7);axs[0].set_xlabel('p1 + p2');axs[0].set_ylabel('Returned score')
    axs[0].set_title('Regularized near-zero channels',color=NAVY,fontweight='bold');axs[0].grid(alpha=.2)
    margin=[float(x['margin']) for x in r]
    axs[1].hist(margin,bins=28,color=CYAN,alpha=.9)
    axs[1].axvline(0,c=ORANGE,lw=2,ls='--',label='Decision threshold')
    axs[1].set_xlabel('Score − threshold');axs[1].set_ylabel('Synthetic sample count')
    axs[1].set_title('Decision margins across three input traces',color=NAVY,fontweight='bold')
    axs[1].legend();axs[1].grid(alpha=.2)
    fig.suptitle('Input-domain and decision-boundary checks',color=NAVY,fontsize=16,fontweight='bold')
    fig.tight_layout(rect=(0,0,1,.95));save(fig,path)

